import {
  Body,
  Controller,
  Get,
  Headers,
  HttpCode,
  HttpStatus,
  Param,
  ParseUUIDPipe,
  Post,
  Query,
  UseGuards,
} from '@nestjs/common';
import {
  ApiBadRequestResponse,
  ApiBearerAuth,
  ApiConflictResponse,
  ApiCreatedResponse,
  ApiHeader,
  ApiNotFoundResponse,
  ApiOkResponse,
  ApiOperation,
  ApiTags,
  ApiUnauthorizedResponse,
  ApiUnprocessableEntityResponse,
} from '@nestjs/swagger';
import { Throttle } from '@nestjs/throttler';

import { JwtAuthGuard } from '../../auth/guards/jwt-auth.guard';
import { CurrentUserId } from '../../cart/decorators/current-user-id.decorator';
import { ApiPaginatedResponse } from '../../common/decorators/api-paginated-response.decorator';
import { PaginatedResponseDto } from '../../common/dto/paginated-response.dto';
import { CancelOrderDto } from '../dto/cancel-order.dto';
import { CreateOrderDto } from '../dto/create-order.dto';
import { OrderListQueryDto } from '../dto/order-list-query.dto';
import { OrderDetailDto, OrderSummaryDto } from '../dto/order-response.dto';
import { OrderReadService } from '../services/order-read.service';
import { OrdersService } from '../services/orders.service';

/**
 * Order endpoints for the authenticated customer.
 *
 * Every route works only on the orders of the user in the access token.
 * Another user's order is reported as not found.
 */
@ApiTags('Orders')
@ApiBearerAuth('access-token')
@ApiUnauthorizedResponse({ description: 'Missing or invalid access token.' })
@UseGuards(JwtAuthGuard)
@Controller('orders')
export class OrdersController {
  /**
   * Injects the order services.
   *
   * @param ordersService Checkout and cancellation.
   * @param readService Order reads.
   */
  constructor(
    private readonly ordersService: OrdersService,
    private readonly readService: OrderReadService,
  ) {}

  /**
   * Places an order from the cart.
   *
   * @param userId Authenticated user id.
   * @param idempotencyKey Value of the Idempotency-Key header.
   * @param dto Delivery details.
   * @returns The created order (or the original one when the request is repeated).
   */
  @Post()
  @Throttle({ default: { limit: 10, ttl: 60000 } })
  @ApiHeader({
    name: 'Idempotency-Key',
    required: true,
    description:
      'A unique value (16 to 64 letters, digits, "_" or "-") generated by the client for each purchase attempt. Repeating the request with the same key returns the same order.',
    example: 'checkout-7f3a9c1e-2b4d-4e8a',
  })
  @ApiOperation({
    summary: 'Place an order from my cart',
    description:
      'Deducts the stock, freezes names and prices, and empties the cart in one transaction. Payment is cash on delivery.',
  })
  @ApiCreatedResponse({ type: OrderDetailDto })
  @ApiBadRequestResponse({
    description: 'Invalid data, or the Idempotency-Key header is missing.',
  })
  @ApiUnprocessableEntityResponse({
    description: 'CART_EMPTY or TOO_MANY_OPEN_ORDERS.',
  })
  @ApiConflictResponse({
    description:
      'CHECKOUT_ITEMS_UNAVAILABLE: some items cannot be ordered. The body lists each item with its issue and the available quantity.',
  })
  create(
    @CurrentUserId() userId: string,
    @Headers('idempotency-key') idempotencyKey: string | undefined,
    @Body() dto: CreateOrderDto,
  ): Promise<OrderDetailDto> {
    return this.ordersService.checkout(userId, idempotencyKey, dto);
  }

  /**
   * Lists the customer's orders.
   *
   * @param userId Authenticated user id.
   * @param query Status filter and pagination.
   * @returns A page of orders, newest first.
   */
  @Get()
  @ApiOperation({ summary: 'List my orders (paginated)' })
  @ApiPaginatedResponse(OrderSummaryDto)
  findAll(
    @CurrentUserId() userId: string,
    @Query() query: OrderListQueryDto,
  ): Promise<PaginatedResponseDto<OrderSummaryDto>> {
    return this.readService.listForCustomer(userId, query);
  }

  /**
   * Retrieves one of the customer's orders.
   *
   * @param userId Authenticated user id.
   * @param id Order UUID.
   * @returns The order details.
   */
  @Get(':id')
  @ApiOperation({ summary: 'Get one of my orders' })
  @ApiOkResponse({ type: OrderDetailDto })
  @ApiNotFoundResponse({
    description: 'The order does not exist or belongs to another user.',
  })
  findOne(
    @CurrentUserId() userId: string,
    @Param('id', ParseUUIDPipe) id: string,
  ): Promise<OrderDetailDto> {
    return this.readService.findDetailForCustomer(userId, id);
  }

  /**
   * Cancels one of the customer's orders while it is PENDING.
   *
   * @param userId Authenticated user id.
   * @param id Order UUID.
   * @param dto Optional reason.
   * @returns The cancelled order.
   */
  @Post(':id/cancel')
  @HttpCode(HttpStatus.OK)
  @ApiOperation({
    summary: 'Cancel my order',
    description:
      'Allowed only while the order is PENDING. The stock is put back. Cancelling an already cancelled order changes nothing.',
  })
  @ApiOkResponse({ type: OrderDetailDto })
  @ApiNotFoundResponse({
    description: 'The order does not exist or belongs to another user.',
  })
  @ApiConflictResponse({
    description: 'INVALID_STATUS_TRANSITION: the order is no longer PENDING.',
  })
  cancel(
    @CurrentUserId() userId: string,
    @Param('id', ParseUUIDPipe) id: string,
    @Body() dto: CancelOrderDto,
  ): Promise<OrderDetailDto> {
    return this.ordersService.cancel(userId, id, dto);
  }
}